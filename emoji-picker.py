def load_theme_colors():
    global \
        BG_COLOR, \
        ACCENT_COLOR, \
        TEXT_COLOR, \
        TEXT_DIM, \
        CARD_BG, \
        CARD_HOVER, \
        BORDER_COLOR
    if not os.path.exists(CURRENT_THEME_FILE):
        return
    theme = ""
    with open(CURRENT_THEME_FILE, "r") as f:
        theme = f.read().strip()
    conf = os.path.join(THEMES_DIR, theme, "theme.conf")
    if not os.path.exists(conf):
        return
    colors = {}
    with open(conf, "r") as f:
        for line in f:
            line = line.strip()
            if "=" in line and not line.startswith("#"):
                key, val = line.split("=", 1)
                colors[key.strip()] = val.strip().strip('"').strip("'")
    BG_COLOR = colors.get("BG", BG_COLOR)
    ACCENT_COLOR = colors.get("ACCENT", ACCENT_COLOR)
    TEXT_COLOR = colors.get("FG", TEXT_COLOR)
    CARD_BG = colors.get("SURFACE", CARD_BG)
    CARD_HOVER = colors.get("HOVER", CARD_HOVER)
    BORDER_COLOR = colors.get("OUTLINE", BORDER_COLOR)


def copy_to_clipboard(text):
    try:
        subprocess.run(["wl-copy"], input=text.encode(), check=True)
    except Exception:
        pass


class EmojiPicker(Gtk.Window):
    def __init__(self):
        super().__init__(title="LGL Emoji Picker")
        self.set_decorated(False)
        self.set_resizable(False)
        self.set_position(Gtk.WindowPosition.CENTER)
        self.set_keep_above(True)
        self.set_type_hint(Gdk.WindowTypeHint.UTILITY)
        self.buttons = []
        self.filtered = []

        main = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=0)
        main.modify_bg(Gtk.StateType.NORMAL, Gdk.color_parse(BG_COLOR))

        # Search bar
        search_box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
        search_box.set_border_width(16)
        self.search = Gtk.SearchEntry()
        self.search.set_placeholder_text("Search emoji...")
        self.search.connect("search-changed", self.on_search)
        self.search.connect("activate", self.on_search_activate)
        self.search.modify_bg(Gtk.StateType.NORMAL, Gdk.color_parse(CARD_BG))
        self.search.modify_text(Gtk.StateType.NORMAL, Gdk.color_parse(TEXT_COLOR))
        self.search.set_size_request(400, -1)
        search_box.pack_start(self.search, True, True, 0)
        main.pack_start(search_box, False, False, 0)

        # Recent row
        self.recent_box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=8)
        self.recent_box.set_margin_left(16)
        self.recent_box.set_margin_right(16)
        self.recent_box.set_margin_bottom(8)

        recent_label = Gtk.Label(label="Recent")
        recent_label.set_halign(Gtk.Align.CENTER)
        recent_label.modify_fg(Gtk.StateType.NORMAL, Gdk.color_parse(TEXT_DIM))
        recent_label.modify_font(Pango.FontDescription("JetBrains Mono Bold 10"))
        self.recent_box.pack_start(recent_label, False, False, 0)

        self.recent_row = Gtk.Grid()
        self.recent_row.set_column_spacing(4)
        self.recent_row.set_row_spacing(4)
        self.recent_row.set_halign(Gtk.Align.CENTER)
        self.recent_box.pack_start(self.recent_row, False, False, 0)
        main.pack_start(self.recent_box, False, False, 0)

        # Scrollable grid
        scrolled = Gtk.ScrolledWindow()
        scrolled.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
        scrolled.set_margin_left(16)
        scrolled.set_margin_right(16)
        scrolled.set_margin_bottom(16)

        self.grid = Gtk.Grid()
        self.grid.set_column_spacing(4)
        self.grid.set_row_spacing(4)
        self.grid.set_halign(Gtk.Align.CENTER)
        scrolled.add(self.grid)
        main.pack_start(scrolled, True, True, 0)

        self.add(main)

        screen = Gdk.Screen.get_default()
        w = min(int(screen.get_width() * 0.5), 700)
        h = min(int(screen.get_height() * 0.55), 600)
        self.set_size_request(w, h)

        self.connect("key-press-event", self.on_key)
        self.connect("destroy", Gtk.main_quit)

        self.recent_emojis = load_recent()
        self.populate_recent()
        self.populate(EMOJIS)
        self.show_all()
        self.search.grab_focus()

    def make_emoji_btn(self, emoji, size=56):
        btn = Gtk.Button(label=emoji)
        btn.set_relief(Gtk.ReliefStyle.NONE)
        btn.modify_font(Pango.FontDescription(f"Sans {EMOJI_SIZE}"))
        btn.set_size_request(size, size)
        btn.connect("clicked", self.on_emoji_click, emoji)
        return btn

    def populate_recent(self):
        for child in self.recent_row.get_children():
            self.recent_row.remove(child)
        if not self.recent_emojis:
            self.recent_box.hide()
            return
        self.recent_box.show()
        for idx, emoji in enumerate(self.recent_emojis):
            btn = self.make_emoji_btn(emoji, size=48)
            self.recent_row.attach(btn, idx % GRID_COLS, idx // GRID_COLS, 1, 1)
            btn.show_all()

    def populate(self, emojis):
        for child in self.grid.get_children():
            self.grid.remove(child)
        self.buttons.clear()
        self.filtered = list(emojis)

        for idx, (emoji, name) in enumerate(emojis):
            btn = self.make_emoji_btn(emoji)
            self.grid.attach(btn, idx % GRID_COLS, idx // GRID_COLS, 1, 1)
            self.buttons.append((btn, emoji, name))
            btn.show_all()

    def on_search(self, entry):
        query = entry.get_text().lower()
        if not query:
            self.recent_box.show()
            self.populate(EMOJIS)
            return
        self.recent_box.hide()
        filtered = [(e, n) for e, n in EMOJIS if query in n.lower() or query in e]
        self.populate(filtered)

    def on_search_activate(self, entry):
        if self.filtered:
            self.select_emoji(self.filtered[0][0])

    def on_emoji_click(self, btn, emoji):
        self.select_emoji(emoji)

    def select_emoji(self, emoji):
        save_recent(emoji)
        copy_to_clipboard(emoji)
        self.close()

    def on_key(self, widget, event):
        if event.keyval == Gdk.KEY_Escape:
            self.close()
        return False


